const mongoose = require('mongoose');

const RoomSchema = new mongoose.Schema({
  id: String,
  name: String,
  type: String,
  x: Number,
  y: Number,
  width: Number,
  height: Number,
  color: String,
  wallColor: String,
  floorColor: String,
  ceilingColor: String,
  wallMaterial: String,
  floorMaterial: String,
  ceilingMaterial: String,
  rotation: Number,
  doors: [mongoose.Schema.Types.Mixed],
  windows: [mongoose.Schema.Types.Mixed],
});

const DesignSchema = new mongoose.Schema({
  user: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
  name: { type: String, required: true },
  landLength: Number,
  landWidth: Number,
  landArea: Number,
  plot: mongoose.Schema.Types.Mixed,
  roadFacing: String,
  floors: Number,
  activeFloor: Number,
  houseType: String,
  budget: Number,
  rooms: [RoomSchema],
  floorLayouts: { type: [[RoomSchema]], default: undefined },
  floorDetails: { type: [mongoose.Schema.Types.Mixed], default: undefined },
  plans: { type: [mongoose.Schema.Types.Mixed], default: undefined },
  currentPlanIndex: Number,
  wallColor: { type: String, default: '#FFFFFF' },
  floorColor: { type: String, default: '#D2B48C' },
  ceilingColor: String,
  wallMaterial: String,
  floorMaterial: String,
  ceilingMaterial: String,
  roofStyle: { type: String, default: 'flat' },
  roofColor: { type: String, default: '#8B4513' },
  showFurniture: Boolean,
  furnitureTheme: String,
  dayMode: Boolean,
  houseView: mongoose.Schema.Types.Mixed,
  lighting: mongoose.Schema.Types.Mixed,
  costEstimate: {
    builtUpArea: Number,
    costPerSqFt: Number,
    structuralCost: Number,
    finishingCost: Number,
    totalCost: Number,
  },
  createdAt: { type: Date, default: Date.now },
  updatedAt: { type: Date, default: Date.now },
});

module.exports = mongoose.model('Design', DesignSchema);
